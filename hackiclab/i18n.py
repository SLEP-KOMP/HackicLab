def _windows_ui_language() -> str | None:
    """Язык интерфейса Windows по данным системы, без зависимости от Qt.

    Qt до создания QApplication отдаёт «C»/«en-US», поэтому при запуске
    основным источником служит GetUserDefaultUILanguage.
    """
    if sys.platform != "win32":
        return None
    try:
        import ctypes

        kernel = ctypes.windll.kernel32
        lang_id = int(kernel.GetUserDefaultUILanguage())
        if not lang_id:
            lang_id = int(kernel.GetSystemDefaultUILanguage())
    except Exception:
        return None
    primary = lang_id & 0x3FF
    return "ru" if primary == 0x19 else "en"


def detect_system_language() -> str:
    """Язык интерфейса по системе: русский для ru-локалей, иначе английский.

    Нужен для первого запуска: пользователь из США должен сразу получить
    английский интерфейс. Явный выбор в настройках важнее — он проверяется до
    этой функции.
    """
    forced = _windows_ui_language()
    if forced is not None:
        return forced
    try:
        from PySide6.QtCore import QLocale

        names = list(QLocale.system().uiLanguages()) or [QLocale.system().name()]
        for name in names:
            code = (name or "").replace("_", "-").split("-")[0].lower()
            if code:
                return code if code in LANG_CODES else "en"
    except Exception:
        pass
    try:
        import locale

        code = (locale.getlocale()[0] or "")[:2].lower()
        if code in LANG_CODES:
            return code
    except Exception:
        pass
    return "en"


class Tr:
    """Обёртка локализации. t("key") возвращает перевод на текущий язык."""

    def __init__(self, lang: str | None = None):
        lang = lang or detect_system_language()
        self.lang = lang if lang in T else "ru"

    def set_lang(self, lang: str):
        if lang in T:
            self.lang = lang

    def t(self, key: str) -> str:
        return T[self.lang].get(key) or T["ru"].get(key) or key

    def issue(self, code: str, field: str, default: str = "") -> str:
        """Заголовок/рекомендация проблемы по коду: EN или исходный текст."""
        if self.lang == "ru":
            return default
        pair = ISSUE_EN.get(code)
        if not pair:
            return default
        return pair[0] if field == "title" else pair[1]

    @property
    def current(self) -> str:
        return self.lang


